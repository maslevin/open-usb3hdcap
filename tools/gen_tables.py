"""Generate lib/hdcap_tables.c: per-input register tables, from USBPcap captures of the Windows driver.

Each table is the I2C write burst the device received between the GPIO-45 reset pulse that starts an
input switch and the point where streaming begins, with:
  - reads dropped,
  - the GPIO pulse itself dropped (hdcap_select_input() issues it),
  - repeated writes collapsed to their first occurrence (polling loops write the same values over and
    over), with a final-state check that appends any write needed to reproduce the captured end state,
  - MST3367 bank selects (reg 0x00) folded into each entry's bank field,
  - pauses >= 5 ms kept (capped at 100 ms).

usage: gen_tables.py CAPTURE_DIR > lib/hdcap_tables.c
"""
import datetime
import os
import struct
import sys

# name, capture, USBPcap device address, start, end (UTC), description
WINDOWS = [
    ('hdmi', 'c17_hdmi_startup.pcap', 11, '03:46:54.26', '03:46:55.20',
     'HDMI (MST3367 digital), recorded with a 1280x720p60 source; includes post-lock colour-space and output setup'),
    ('vga', 'c05_replug_streamcatcher.pcap', 5, '00:12:50.74', '00:12:53.39',
     'VGA (MST3367 analog RGB), recorded with a 640x480@60 source (h-total 880)'),
    ('component', 'c15_input_switch.pcap', 9, '02:54:27.90', '02:54:30.83',
     'Component YPbPr (MST3367 analog), recorded with a 480i source'),
    ('composite', 'c12_composite.pcap', 7, '02:13:40.03', '02:13:48.54',
     'Composite (TW9900), recorded with an NTSC source'),
    ('svideo', 'c13_svideo.pcap', 9, '02:41:52.94', '02:41:53.80',
     'S-Video (TW9900), recorded with an NTSC source'),
]

NAMES = {0x9C: 'MST3367', 0x88: 'TW9900', 0x94: 'CS53L21', 0x98: 'CPLD'}


def read_ops(path, dev, t0s, t1s):
    f = open(path, 'rb')
    f.read(24)
    setups, ops, day = {}, [], None
    while True:
        h = f.read(16)
        if len(h) < 16:
            break
        ts, tu, incl, _ = struct.unpack('<IIII', h)
        d = f.read(incl)
        t = ts + tu / 1e6
        if day is None:
            day = datetime.datetime.fromtimestamp(t, datetime.timezone.utc).date()

            def at(s):
                hh, mm, ss = s.split(':')
                return datetime.datetime(day.year, day.month, day.day, int(hh), int(mm),
                                         tzinfo=datetime.timezone.utc).timestamp() + float(ss)
            t0, t1 = at(t0s), at(t1s)
        hl, irp, st, fn, info, bus, dv, ep, tt, dl = struct.unpack_from('<HQIHBHHBBI', d)
        if dv != dev or tt != 2:
            continue
        if d[27] == 0 and not (info & 1):
            setups[irp] = (t, d[hl:])
        elif (info & 1) and irp in setups:
            ts0, sd = setups.pop(irp)
            if not (t0 <= ts0 < t1):
                continue
            rt, rq, wv, wi, wl = struct.unpack('<BBHHH', sd[:8])
            if rt == 0x40 and rq == 0xC0 and wl == 1 and st == 0:
                ops.append((ts0, wv, wi, sd[8]))
    return ops


def build(ops):
    bank = None
    entries = []          # (t, addr, bank, reg, val)
    for t, addr, reg, val in ops:
        if addr == 0x9C and reg == 0x00:
            bank = val
            continue
        entries.append((t, addr, bank if addr == 0x9C else 0xFF, reg, val))
    final = {}
    for e in entries:
        final[e[1:4]] = e[4]
    seen, out = set(), []
    for e in entries:
        if e[1:] in seen:
            continue
        seen.add(e[1:])
        out.append(e)
    state = {}
    for e in out:
        state[e[1:4]] = e[4]
    for k, v in final.items():           # restore captured end state where collapsing changed it
        if state.get(k) != v:
            out.append((out[-1][0], *k, v))
    return out


def main():
    cdir = sys.argv[1]
    print('/* SPDX-License-Identifier: GPL-2.0-or-later')
    print(' * Copyright (C) 2026 Matt Slevinsky */')
    print('/* Generated by tools/gen_tables.py from USBPcap captures of the vendor driver. Do not edit.')
    print(' * Each entry: { i2c address, MST3367 bank (0xFF = not banked), register, value, delay before (ms) }.')
    print(' * These are observed bus writes, kept as data until each can be derived from chip documentation. */')
    print('#include "hdcap_tables.h"\n')
    for name, cap, dev, t0, t1, desc in WINDOWS:
        ops = read_ops(os.path.join(cdir, cap), dev, t0, t1)
        tab = build(ops)
        print(f'/* {desc}.\n * Source: {cap}, device {dev}, {t0}..{t1} UTC: {len(ops)} writes -> {len(tab)} entries. */')
        print(f'const hdcap_reg_write hdcap_table_{name}[] = {{')
        prev = None
        for t, addr, bank, reg, val in tab:
            delay = 0 if prev is None else int(round((t - prev) * 1000))
            delay = min(delay, 100) if delay >= 5 else 0
            prev = t
            print(f'    {{ 0x{addr:02X}, 0x{bank:02X}, 0x{reg:02X}, 0x{val:02X}, {delay:3d} }}, /* {NAMES.get(addr, "?")} */')
        print('};')
        print(f'const size_t hdcap_table_{name}_len = sizeof(hdcap_table_{name}) / sizeof(hdcap_table_{name}[0]);\n')


main()
