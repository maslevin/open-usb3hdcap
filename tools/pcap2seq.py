"""Convert a window of a USBPcap capture of the USB3HDCAP into a replayable sequence file.

The sequence file is plain text, one operation per line (see sequences/README.md):
    i2c_w <addr> <reg> <val>     vendor request 0xC0 OUT: I2C register write
    i2c_r <addr> <reg> [# val]   vendor request 0xC0 IN:  I2C register read (observed value as comment)
    vreq  <bReq> <wValue> <wIndex>   other vendor OUT request without data (C1 GPIO, C2, C5, C6, C7, ...)
    alt   <iface> <alt>          SET_INTERFACE
    delay <ms>                   pause observed between operations (capped)

usage: pcap2seq.py CAPTURE.pcap --dev N --from HH:MM:SS.f --to HH:MM:SS.f [--max-delay MS] > out.seq
Only standard-library Python is used, so this runs anywhere.
"""
import argparse
import datetime
import struct
import sys

ap = argparse.ArgumentParser()
ap.add_argument('pcap')
ap.add_argument('--dev', type=int, required=True, help='USBPcap device address of the USB3HDCAP')
ap.add_argument('--from', dest='t0', required=True, help='UTC time HH:MM:SS.f (date taken from the capture)')
ap.add_argument('--to', dest='t1', required=True)
ap.add_argument('--max-delay', type=int, default=500, help='cap for inserted delays in ms')
ap.add_argument('--min-delay', type=int, default=3, help='gaps shorter than this are not emitted')
a = ap.parse_args()

f = open(a.pcap, 'rb')
gh = f.read(24)
if struct.unpack('<I', gh[20:24])[0] != 249:
    sys.exit('not a USBPcap (DLT 249) capture')


def packets():
    while True:
        h = f.read(16)
        if len(h) < 16:
            return
        ts, tu, incl, _ = struct.unpack('<IIII', h)
        d = f.read(incl)
        hl, irp, st, fn, info, bus, dev, ep, tt, dl = struct.unpack_from('<HQIHBHHBBI', d)
        yield ts + tu / 1e6, dict(irp=irp, st=st, out=not (info & 1), dev=dev, tt=tt, hl=hl,
                                  stage=d[27] if tt == 2 and hl >= 28 else None, data=d[hl:])


win = None
ops = []          # (t, text)
setups = {}
for t, p in packets():
    if win is None:
        day = datetime.datetime.fromtimestamp(t, datetime.timezone.utc).date()

        def at(s):
            h, m, sec = s.split(':')
            return datetime.datetime(day.year, day.month, day.day, int(h), int(m),
                                     tzinfo=datetime.timezone.utc).timestamp() + float(sec)
        win = (at(a.t0), at(a.t1))
    if p['dev'] != a.dev or p['tt'] != 2:
        continue
    if p['stage'] == 0 and p['out']:
        setups[p['irp']] = (t, p['data'])
        continue
    if p['out'] or p['irp'] not in setups or p['stage'] not in (1, 3):
        continue
    t0, sd = setups.pop(p['irp'])
    if not (win[0] <= t0 < win[1]):
        continue
    rt, rq, wv, wi, wl = struct.unpack('<BBHHH', sd[:8])
    failed = p['st'] != 0
    note = f'   # status {p["st"]:#010x}' if failed else ''
    if rt == 0x40 and rq == 0xC0 and wl == 1:
        ops.append((t0, f'i2c_w 0x{wv:02x} 0x{wi:02x} 0x{sd[8]:02x}{note}'))
    elif rt == 0xC0 and rq == 0xC0 and wl == 1:
        val = f'0x{p["data"][0]:02x}' if p['data'] else '?'
        ops.append((t0, f'i2c_r 0x{wv:02x} 0x{wi:02x}   # {val}{note.replace("   #", ";")}'))
    elif rt == 0x40 and wl == 0:
        ops.append((t0, f'vreq 0x{rq:02x} 0x{wv:04x} 0x{wi:04x}{note}'))
    elif rt == 0x01 and rq == 11:
        ops.append((t0, f'alt {wi} {wv}'))
    elif rt & 0x60 == 0x40:
        ops.append((t0, f'# unsupported vendor request bmRT={rt:#04x} bReq={rq:#04x} wValue={wv:#06x} wIndex={wi:#06x} wLength={wl}'))

print(f'# generated by tools/pcap2seq.py from {a.pcap.split("/")[-1]}, device {a.dev}, {a.t0}..{a.t1} UTC')
print(f'# {len(ops)} operations')
prev = None
for t, text in ops:
    if prev is not None:
        gap = int(round((t - prev) * 1000))
        if gap >= a.min_delay:
            print(f'delay {min(gap, a.max_delay)}')
    print(text)
    prev = t
